-- -----------------------------------------------------------------------------
-- Functions (SECURITY DEFINER helpers used by RLS policies)
-- -----------------------------------------------------------------------------
create or replace function public.current_employee_id()
  returns bigint
  language sql
  security definer
  set search_path to 'public'
as $function$
  select e.id from public.employees e where e.auth_id = auth.uid() limit 1;
$function$;

create or replace function public.is_manager()
  returns boolean
  language sql
  security definer
  set search_path to 'public'
as $function$
  select exists (
    select 1 from public.employees e
    where e.auth_id = auth.uid()
      and e.role in ('Manager', 'Site Manager', 'Park Admin')
  );
$function$;

