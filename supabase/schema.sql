-- ============================================================================
-- Pine Lake Recreation — Production schema + Row-Level Security
-- ----------------------------------------------------------------------------
-- Run this in the Supabase SQL editor (or via the CLI) to provision a live
-- backend. The app auto-switches from mock mode to Supabase as soon as
-- VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY are set.
--
-- Auth model:
--   * Managers sign in with a real email + password (Supabase Auth user).
--   * Employees are linked to an auth user via employees.auth_id and clock in
--     using the internal credential emp_<id>@pinelake.internal.
--   * Role lives on the employees row; is_manager() reads it to gate writes.
-- ============================================================================

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table if not exists public.employees (
  id              bigint generated by default as identity primary key,
  auth_id         uuid references auth.users (id) on delete set null,
  name            text not null,
  role            text not null default 'Waterfront',
  base_rate       numeric(10,2) not null default 0,
  bonus_rate      numeric(10,2) not null default 0,
  pin             text,
  auth_method     text not null default 'pin',          -- 'pin' | 'face'
  avatar          text,
  fed_tax_rate    numeric(5,2) not null default 12,
  state_tax_rate  numeric(5,2) not null default 5.5,
  county_tax_rate numeric(5,2) not null default 0,
  fica_tax_rate   numeric(5,2) not null default 7.65,
  certifications  jsonb not null default '[]'::jsonb,    -- [{ type, expires }]
  created_at      timestamptz not null default now()
);

create table if not exists public.clock_logs (
  id            bigint generated by default as identity primary key,
  employee_id   bigint not null references public.employees (id) on delete cascade,
  action        text not null,                           -- IN | OUT | BREAK_START | BREAK_END | AUTO-OUT
  photo_base64  text,
  signature     text,
  suspicious_gps boolean not null default false,
  created_at    timestamptz not null default now()
);
create index if not exists clock_logs_employee_idx on public.clock_logs (employee_id, created_at desc);

create table if not exists public.schedules (
  id          bigint generated by default as identity primary key,
  week_key    text not null,                             -- Sunday ISO date of the week
  day         text not null,                             -- 'Monday' .. 'Sunday'
  employee_id bigint not null references public.employees (id) on delete cascade,
  shift_time  text not null default '',                  -- '09:00-17:00|Role' or 'OFF'
  version_ts  bigint not null default 0,
  unique (week_key, day, employee_id)
);

create table if not exists public.stations (
  id        bigint generated by default as identity primary key,
  name      text not null,
  latitude  numeric(9,6) not null,
  longitude numeric(9,6) not null,
  radius    numeric(7,2) not null default 50              -- geofence radius in meters
);

create table if not exists public.announcements (
  id         bigint generated by default as identity primary key,
  text       text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.payroll_history (
  id                bigint generated by default as identity primary key,
  employee_id       bigint not null references public.employees (id) on delete cascade,
  week_start_date   date not null,
  total_hours       numeric(10,2) not null default 0,
  pay_rate_at_time  numeric(10,2) not null default 0,
  gross_pay         numeric(12,2) not null default 0,
  fed_tax           numeric(12,2) not null default 0,
  state_tax         numeric(12,2) not null default 0,
  county_tax        numeric(12,2) not null default 0,
  fica_tax          numeric(12,2) not null default 0,
  employer_tax      numeric(12,2) not null default 0,
  total_cost        numeric(12,2) not null default 0,
  net_pay           numeric(12,2) not null default 0,
  created_at        timestamptz not null default now()
);

create table if not exists public.time_off_requests (
  id          bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees (id) on delete cascade,
  type        text not null default 'Time Off',          -- 'Time Off' | 'Shift Swap' | 'Sick'
  start_date  date not null,
  end_date    date not null,
  reason      text,
  status      text not null default 'pending',           -- 'pending' | 'approved' | 'denied'
  -- Shift-swap matching: the coworker and weekday this shift is being swapped with
  swap_with   bigint references public.employees (id) on delete set null,
  swap_day    text,                                      -- 'Monday' .. 'Sunday'
  reviewed_by bigint references public.employees (id) on delete set null,
  reviewed_at timestamptz,
  created_at  timestamptz not null default now()
);
create index if not exists time_off_employee_idx on public.time_off_requests (employee_id, created_at desc);

-- ---------------------------------------------------------------------------
-- Helper: is the current auth user a manager?
-- ---------------------------------------------------------------------------
create or replace function public.is_manager()
returns boolean
language sql
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.employees e
    where e.auth_id = auth.uid()
      and e.role in ('Manager', 'Site Manager', 'Park Admin')
  );
$$;

-- Helper: the employees.id that belongs to the current auth user
create or replace function public.current_employee_id()
returns bigint
language sql
security definer
set search_path = public
as $$
  select e.id from public.employees e where e.auth_id = auth.uid() limit 1;
$$;

-- ---------------------------------------------------------------------------
-- Row-Level Security
-- ---------------------------------------------------------------------------
alter table public.employees        enable row level security;
alter table public.clock_logs       enable row level security;
alter table public.schedules        enable row level security;
alter table public.stations         enable row level security;
alter table public.announcements    enable row level security;
alter table public.payroll_history  enable row level security;
alter table public.time_off_requests enable row level security;

-- EMPLOYEES: everyone authenticated can read the roster (needed for the kiosk).
-- Only managers may insert/update/delete staff records.
create policy "employees readable" on public.employees
  for select to authenticated using (true);
create policy "employees managed by managers" on public.employees
  for all to authenticated using (public.is_manager()) with check (public.is_manager());

-- CLOCK LOGS: an employee may read and insert only their OWN punches;
-- managers can read and write everything (for corrections).
create policy "clock_logs read own or manager" on public.clock_logs
  for select to authenticated
  using (employee_id = public.current_employee_id() or public.is_manager());
create policy "clock_logs insert own" on public.clock_logs
  for insert to authenticated
  with check (employee_id = public.current_employee_id() or public.is_manager());
create policy "clock_logs managers edit" on public.clock_logs
  for update to authenticated using (public.is_manager()) with check (public.is_manager());
create policy "clock_logs managers delete" on public.clock_logs
  for delete to authenticated using (public.is_manager());

-- SCHEDULES: any authenticated user can read (employees see their shifts);
-- only managers may write.
create policy "schedules readable" on public.schedules
  for select to authenticated using (true);
create policy "schedules managed by managers" on public.schedules
  for all to authenticated using (public.is_manager()) with check (public.is_manager());

-- STATIONS: readable by all (geofence checks); managed by managers.
create policy "stations readable" on public.stations
  for select to authenticated using (true);
create policy "stations managed by managers" on public.stations
  for all to authenticated using (public.is_manager()) with check (public.is_manager());

-- ANNOUNCEMENTS: readable by all; posted/removed by managers.
create policy "announcements readable" on public.announcements
  for select to authenticated using (true);
create policy "announcements managed by managers" on public.announcements
  for all to authenticated using (public.is_manager()) with check (public.is_manager());

-- PAYROLL HISTORY: an employee may read only their own; managers full access.
create policy "payroll read own or manager" on public.payroll_history
  for select to authenticated
  using (employee_id = public.current_employee_id() or public.is_manager());
create policy "payroll managed by managers" on public.payroll_history
  for all to authenticated using (public.is_manager()) with check (public.is_manager());

-- TIME OFF: employees create and read their own requests; managers review all.
create policy "timeoff read own or manager" on public.time_off_requests
  for select to authenticated
  using (employee_id = public.current_employee_id() or public.is_manager());
create policy "timeoff insert own" on public.time_off_requests
  for insert to authenticated
  with check (employee_id = public.current_employee_id());
create policy "timeoff managers review" on public.time_off_requests
  for update to authenticated using (public.is_manager()) with check (public.is_manager());
create policy "timeoff delete own or manager" on public.time_off_requests
  for delete to authenticated
  using (employee_id = public.current_employee_id() or public.is_manager());

